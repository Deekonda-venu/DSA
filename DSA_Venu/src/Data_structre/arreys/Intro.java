//    📌 Array – Simple Notes
//
//    An array is a basic data structure used to store multiple values of the same type in a single variable. All elements in an array are stored in continuous memory locations, which helps in fast access. Each element is identified using an index, and indexing usually starts from 0. Because of this structure, arrays allow direct access (O(1)) to any element using its index.
//
//            📌 Why We Need Arrays
//
//    Arrays are used to store large amounts of similar data efficiently. Instead of creating many separate variables (like marks1, marks2, marks3…), we can store all values in one array. This makes the code clean, easy to manage, and scalable, especially when the number of elements is large.
//
//📌 Types of Arrays
//
//    Arrays can be classified based on size and dimensions.
//    A fixed-size array has a predefined size that cannot be changed during execution, while a dynamic array (like ArrayList in Java) can grow or shrink as needed.
//    Based on dimensions, arrays can be 1D (linear list), 2D (matrix format), or multi-dimensional for more complex data representation.
//
//            📌 Operations on Arrays
//
//    Common operations performed on arrays include traversal (visiting elements), insertion, deletion, and searching. Searching can be done using linear search or binary search (if the array is sorted).
//
//            📌 Applications of Arrays
//
//    Arrays are widely used in programming for storing and processing data. They are used in matrices, image processing, dynamic programming, and also act as the base for other data structures like stacks and queues. Arrays are also useful as buffers to temporarily store data like streams or network packets.
//
//📌 Advantages of Arrays
//
//    Arrays provide fast and efficient access to elements due to contiguous memory. They are memory-efficient and simple to use. Arrays are also versatile, as they can store different types of data like integers, characters, or objects.
//
//            📌 Disadvantages of Arrays
//
//    The main limitation of arrays is their fixed size, which cannot be changed after creation. Insertion and deletion operations are costly because elements need to be shifted. Also, allocating very large arrays may cause memory issues.
//
//            📌 Final Understanding
//
//    In short, arrays are one of the most fundamental and important data structures in programming. They are simple, fast, and widely used, but they lack flexibility in size and dynamic operations. Because of this, more advanced structures like ArrayList, LinkedList, etc. are used when flexibility is required.
//}
